const assert=require('node:assert/strict');
require('../src/mission-engine.js');
const curriculum=require('../curriculum/llm-nsi.json');
const mission=require('../curriculum/missions/tokenisation.json');
let raw='{"version":2,"records":{}}';
const storage={getItem:()=>raw,setItem:(_,value)=>raw=value};
let engine=NexusMissionEngine.create(curriculum,[mission],storage);
assert.equal(engine.status('M01','premiere'),'unimplemented');
assert.equal(engine.status('M03','premiere'),'available');
assert.throws(()=>engine.mark('M03','premiere','transferer'),/précédentes/);
engine.attempt('M03','premiere');
for(const step of NexusMissionEngine.steps)engine.mark('M03','premiere',step);
assert.equal(engine.status('M03','premiere'),'completed');
assert.equal(engine.status('M03','terminale'),'available');
engine=NexusMissionEngine.create(curriculum,[mission],storage);
assert.equal(engine.record('M03','premiere').attempts,1);
assert.equal(engine.status('M03','premiere'),'completed');
assert.equal(NexusMissionEngine.create(curriculum,[{...mission,version:2}],storage).status('M03','premiere'),'available');
const broken={getItem(){throw Error('blocked')},setItem(){throw Error('full')}};
engine=NexusMissionEngine.create(curriculum,[mission],broken);
engine.mark('M03','premiere','comprendre');assert.equal(engine.persistent(),false);
const next={...mission,id:'M04',moduleDependencies:['M03']};
engine=NexusMissionEngine.create(curriculum,[mission,next],{getItem:()=>null,setItem(){}});
assert.equal(engine.status('M04','premiere'),'locked');
assert.throws(()=>engine.mark('M04','premiere','comprendre'),/verrouillée/);
for(const step of NexusMissionEngine.steps)engine.mark('M03','premiere',step);
assert.equal(engine.status('M04','premiere'),'available');
assert.throws(()=>NexusMissionEngine.create(curriculum,[{...mission,moduleDependencies:['M04']},next],storage),/Cycle/);
assert.equal(NexusMissionEngine.create(curriculum,[mission],{getItem:()=>'{bad',setItem(){}}).status('M03','premiere'),'available');
console.log('MISSION ENGINE PASS: order, persistence, levels, versions, storage failures, locks, cycles');
